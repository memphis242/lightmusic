std::string errnoText(int e) { return std::strerror(e); }

// mkdir -p with mode 0700 for the directories it creates.
bool makeDirs(const std::string &dir, std::string *err) {
    for (std::size_t i = 1; i <= dir.size(); i++) {
        if (i < dir.size() && dir[i] != '/') continue;
        const std::string part = dir.substr(0, i);
        if (::mkdir(part.c_str(), 0700) == 0) continue;
        const int e = errno;
        struct stat sb{};
        if (e == EEXIST && ::stat(part.c_str(), &sb) == 0 && S_ISDIR(sb.st_mode)) continue;
        if (err) *err = std::format("cannot create {}: {}", part, errnoText(e == EEXIST ? ENOTDIR : e));
        return false;
    }
    return true;
}

struct Fd {
    int fd = -1;
    Fd() = default;
    explicit Fd(int f) : fd(f) {}
    Fd(const Fd &) = delete;
    Fd &operator=(const Fd &) = delete;
    ~Fd() {
        if (fd >= 0) (void)::close(fd); // read-only, or a write whose result was already checked
    }
};

