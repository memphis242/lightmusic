std::string errnoText(int e) { return std::strerror(e); }

// mkdir -p with mode 0700 for the directories it creates.
bool makeDirs(const std::string &dir, std::string *err) {
    for (std::size_t i = 1; i <= dir.size(); i++) {
        if (i < dir.size() && dir[i] != '/') continue;
        const std::string part = dir.substr(0, i);
        if (::mkdir(part.c_str(), 0700) == 0) continue;
        const int e = errno;
        struct stat sb{};
        if (e == EEXIST && ::stat(part.c_str(), &sb) == 0 && S_ISDIR(sb.st_mode)) continue;
        if (err) *err = std::format("cannot create {}: {}", part, errnoText(e == EEXIST ? ENOTDIR : e));
        return false;
    }
    return true;
}

bool hasAudioExt(std::string_view name) {
    const auto dot = name.rfind('.');
    if (dot == std::string_view::npos) return false;
    std::string e(name.substr(dot + 1));
    std::transform(e.begin(), e.end(), e.begin(), [](unsigned char c) { return static_cast<char>(std::tolower(c)); });
    return e == "mp3" || e == "flac" || e == "opus" || e == "ogg" || e == "oga";
}

// Rank of a folder image name (lower is preferred), or -1 if it is not one.
int imageRank(std::string_view name) {
    static constexpr std::array<std::string_view, 6> kNames = {"cover.jpg",  "folder.jpg", "cover.jpeg",
                                                               "folder.jpeg", "cover.png",  "folder.png"};
    std::string n(name);
    std::transform(n.begin(), n.end(), n.begin(), [](unsigned char c) { return static_cast<char>(std::tolower(c)); });
    for (std::size_t i = 0; i < kNames.size(); i++)
        if (n == kNames[i]) return static_cast<int>(i);
    return -1;
}

struct DirCloser {
    void operator()(DIR *d) const noexcept { (void)::closedir(d); } // read-only stream: nothing to lose
};

struct Fd {
    int fd = -1;
    Fd() = default;
    explicit Fd(int f) : fd(f) {}
    Fd(const Fd &) = delete;
    Fd &operator=(const Fd &) = delete;
    ~Fd() {
        if (fd >= 0) (void)::close(fd); // read-only, or a write whose result was already checked
    }
};

void stampFile(std::string &s, std::string_view name, const struct stat &sb) {
    s += name;
    s += std::format("\x1f{}\x1f{}.{}\x1e", static_cast<long long>(sb.st_size), static_cast<long long>(sb.st_mtim.tv_sec),
                     static_cast<long long>(sb.st_mtim.tv_nsec));
}

