std::string coversDir(const std::string &cacheDir, std::string *err) {
    if (!cacheDir.empty()) return cacheDir + "/covers";
    if (const char *x = std::getenv("XDG_CACHE_HOME"); x && *x == '/') return std::string(x) + "/lightmusic/covers";
    if (const char *h = std::getenv("HOME"); h && *h) return std::string(h) + "/.cache/lightmusic/covers";
    if (err) *err = "cannot find a cache directory (set XDG_CACHE_HOME or HOME)";
    return {};
}

bool CoverCache::validKey(std::string_view key) {
    return !key.empty() && key.size() <= 64 && std::all_of(key.begin(), key.end(), [](char c) {
        return (c >= '0' && c <= '9') || (c >= 'a' && c <= 'z') || c == '-';
    });
}

bool CoverCache::ensureDir(std::string *err) const { return makeDirs(dir_, err); }

CoverCache::Lookup CoverCache::load(std::string_view key, std::uint64_t stamp, Thumb &out, std::string *err) const {
    LM_ASSERT(validKey(key), "cache keys are generated by us");
    std::string bytes, why;
    if (!readSmallFile(path(key), kThumbFileHeader + kThumbBytes, bytes, &why)) {
        if (errno != ENOENT && err) *err = why;
        return Lookup::Miss;
    }
    std::optional<Thumb> t;
    std::uint64_t got = 0;
    if (!decodeThumbFile(std::span(reinterpret_cast<const std::uint8_t *>(bytes.data()), bytes.size()), t, got, &why)) {
        if (err) *err = path(key) + ": " + why;
        return Lookup::Miss;
    }
    if (got != stamp) return Lookup::Miss;
    if (!t) return Lookup::NoArt;
    out = *t;
    return Lookup::Hit;
}

bool CoverCache::store(std::string_view key, std::uint64_t stamp, const std::optional<Thumb> &t, std::string *err) const {
    LM_ASSERT(validKey(key), "cache keys are generated by us");
    const std::string data = encodeThumbFile(t, stamp);
    const std::string dst = path(key);
    std::string tmp = dir_ + "/." + std::string(key) + ".XXXXXX";
    Fd f(::mkostemp(tmp.data(), O_CLOEXEC));
    if (f.fd < 0) {
        if (err) *err = std::format("cannot create a file in {}: {}", dir_, errnoText(errno));
        return false;
    }
    auto fail = [&](const std::string &what, int e) {
        if (err) *err = std::format("{} {}: {}", what, tmp, errnoText(e));
        (void)::unlink(tmp.c_str()); // best-effort cleanup of our own temporary file
        return false;
    };
    for (std::size_t off = 0; off < data.size();) {
        const ssize_t w = ::write(f.fd, data.data() + off, data.size() - off);
        if (w < 0 && errno == EINTR) continue;
        if (w <= 0) return fail("cannot write", w < 0 ? errno : EIO);
        off += static_cast<std::size_t>(w);
    }
    const int fd = std::exchange(f.fd, -1);
    if (::close(fd) != 0) return fail("cannot write", errno);
    if (::rename(tmp.c_str(), dst.c_str()) != 0) return fail("cannot rename", errno);
    return true;
}

bool readSmallFile(const std::string &path, std::size_t maxBytes, std::string &out, std::string *err) {
    out.clear();
    Fd f(::open(path.c_str(), O_RDONLY | O_CLOEXEC | O_NONBLOCK));
    if (f.fd < 0) {
        const int e = errno;
        if (err) *err = std::format("cannot open {}: {}", path, errnoText(e));
        errno = e;
        return false;
    }
    struct stat sb{};
    if (::fstat(f.fd, &sb) != 0) {
        const int e = errno;
        if (err) *err = std::format("cannot stat {}: {}", path, errnoText(e));
        errno = e;
        return false;
    }
    if (!S_ISREG(sb.st_mode) || sb.st_size < 0 || static_cast<std::uint64_t>(sb.st_size) > maxBytes) {
        if (err)
            *err = S_ISREG(sb.st_mode) ? std::format("{}: too large ({} bytes; limit {})", path,
                                                     static_cast<long long>(sb.st_size), maxBytes)
                                       : std::format("{}: not a regular file", path);
        errno = EINVAL;
        return false;
    }
    out.resize(static_cast<std::size_t>(sb.st_size));
    std::size_t got = 0;
    while (got < out.size()) {
        const ssize_t r = ::read(f.fd, out.data() + got, out.size() - got);
        if (r < 0 && errno == EINTR) continue;
        if (r < 0) {
            const int e = errno;
            if (err) *err = std::format("cannot read {}: {}", path, errnoText(e));
            errno = e;
            return false;
        }
        if (r == 0) break; // shrank meanwhile: use what is there
        got += static_cast<std::size_t>(r);
    }
    out.resize(got);
    return true;
}

bool probeAlbum(const std::string &trackPath, LocalAlbum &out, std::string *err) {
    out = LocalAlbum{};
    const auto slash = trackPath.rfind('/');
    const std::string given = slash == std::string::npos ? "." : slash == 0 ? "/" : trackPath.substr(0, slash);
    std::unique_ptr<char, decltype(&std::free)> real(::realpath(given.c_str(), nullptr), &std::free);
    if (!real) {
        if (err) *err = std::format("cannot resolve {}: {}", given, errnoText(errno));
        return false;
    }
    out.dir = real.get();
    std::unique_ptr<DIR, DirCloser> d(::opendir(out.dir.c_str()));
    if (!d) {
        if (err) *err = std::format("cannot list {}: {}", out.dir, errnoText(errno));
        return false;
    }
    std::string audio, image;
    int rank = INT_MAX;
    struct stat audioSb{}, imageSb{};
    for (;;) {
        errno = 0;
        // readdir() is thread-safe for a stream used by one thread (POSIX 2024, glibc);
        // readdir_r() is deprecated. The stream is local to this call.
        // cppcheck-suppress readdirCalled
        const dirent *e = ::readdir(d.get());
        if (!e) {
            if (errno != 0) {
                if (err) *err = std::format("cannot list {}: {}", out.dir, errnoText(errno));
                return false;
            }
            break;
        }
        const std::string_view name = e->d_name;
        const bool isAudio = hasAudioExt(name);
        const int r = isAudio ? -1 : imageRank(name);
        if (!(isAudio && (audio.empty() || name < audio)) && !(r >= 0 && r < rank)) continue;
        struct stat sb{};
        if (::fstatat(::dirfd(d.get()), e->d_name, &sb, 0) != 0 || !S_ISREG(sb.st_mode)) continue; // vanished, dangling, not a file
        if (isAudio) {
            audio = name;
            audioSb = sb;
        } else {
            image = name;
            rank = r;
            imageSb = sb;
        }
    }
    std::string st;
    if (!audio.empty()) {
        out.audio = out.dir + "/" + audio;
        stampFile(st, audio, audioSb);
    }
    st += '\x1d';
    if (!image.empty()) {
        out.image = out.dir + "/" + image;
        stampFile(st, image, imageSb);
    }
    out.stamp = fnv1a64(st);
    out.key = std::format("l{:016x}", fnv1a64(out.dir));
    return true;
}

bool buildAlbumThumb(const LocalAlbum &a, std::optional<Thumb> &out, std::string *err, const Limits &lim) {
    out.reset();
    std::string why;
    auto note = [&](const std::string &m) { why += (why.empty() ? "" : "; ") + m; };
    if (!a.audio.empty()) {
        std::vector<unsigned char> pic;
        std::string e;
        if (!readEmbeddedPicture(a.audio, pic, &e)) {
            note(e);
        } else if (!pic.empty()) {
            if (auto t = makeThumb(pic, &e, lim)) {
                out = t;
                return true;
            }
            note(std::format("embedded picture of {}: {}", a.audio, e));
        }
    }
    if (!a.image.empty()) {
        std::string bytes, e;
        if (!readSmallFile(a.image, lim.maxBytes, bytes, &e)) {
            note(e);
        } else if (auto t = makeThumb(std::span(reinterpret_cast<const std::uint8_t *>(bytes.data()), bytes.size()), &e,
                                      lim)) {
            out = t;
            return true;
        } else {
            note(std::format("{}: {}", a.image, e));
        }
    }
    if (why.empty()) return true; // no art at all
    if (err) *err = std::move(why);
    return false;
}

bool setBackgroundPriority(std::string *err) {
    sched_param sp{};
    sp.sched_priority = 0;
    const int r = ::pthread_setschedparam(::pthread_self(), SCHED_IDLE, &sp);
    if (r == 0) return true;
    // setpriority() on a thread id changes only that thread on Linux.
    if (::setpriority(PRIO_PROCESS, static_cast<id_t>(::gettid()), 19) == 0) return true;
    if (err) *err = std::format("cannot lower the thread priority: {}; {}", errnoText(r), errnoText(errno));
    return false;
}

